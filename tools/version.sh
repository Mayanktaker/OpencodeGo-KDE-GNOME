#!/usr/bin/env bash
# © Mayanktaker Computers & Web Development | https://mayanktaker.com
# Single source of truth for the project version.
#
#   tools/version.sh sync    # write VERSION into every manifest, label and package name
#   tools/version.sh check   # fail if any of them drifted away from VERSION
#
# The root VERSION file is the only place a version number is authored by hand;
# every other place (KDE metadata, GNOME packaging, the About label, the
# changelog heading) is derived from it by this script.
set -uo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
VERSION_FILE="$ROOT/VERSION"

# Files that carry a version and the pattern that extracts it from each
# gnome-extension/package.sh and gnome-extension/prefs.js are deliberately
# absent: both read the VERSION file / version.js at run time, so they can
# never drift.
METADATA_JSON="$ROOT/metadata.json"
VERSION_JS="$ROOT/gnome-extension/version.js"
CHANGELOG="$ROOT/CHANGELOG.md"

read_version() {
    tr -d '[:space:]' < "$VERSION_FILE"
}

# Prints the version currently stored in a target file, or nothing when absent
detect_version() {
    case "$1" in
        "$METADATA_JSON") sed -nE 's/.*"Version":[[:space:]]*"([^"]+)".*/\1/p' "$METADATA_JSON" | head -1 ;;
        "$VERSION_JS")   sed -nE "s/^export const VERSION = '([^']+)';.*/\1/p" "$VERSION_JS" | head -1 ;;
        "$CHANGELOG")    sed -nE 's/^## v([0-9]+\.[0-9]+\.[0-9]+).*/\1/p' "$CHANGELOG" | head -1 ;;
    esac
}

sync_version() {
    local v="$1"
    # KDE Plasma package metadata
    sed -i -E "s/(\"Version\":[[:space:]]*\")[^\"]+(\")/\1${v}\2/" "$METADATA_JSON"
    # Generated runtime module read by prefs.js
    cat > "$VERSION_JS" <<EOF
// © Mayanktaker Computers & Web Development | https://mayanktaker.com
// Generated by tools/version.sh from the root VERSION file — do not edit by hand
export const VERSION = '${v}';
EOF
    # About label inside the GNOME preferences window reads version.js at run time
    # Top changelog section heading is NOT rewritten here: released sections are
    # immutable, so the new '## vX.Y.Z' section is added by hand and `check`
    # then fails until it exists.
}

check_version() {
    local v="$1" drift=0 target current
    for target in "$METADATA_JSON" "$VERSION_JS" "$CHANGELOG"; do
        current="$(detect_version "$target")"
        if [ "$current" != "$v" ]; then
            echo "version drift: ${target#"$ROOT"/} has '${current:-<none>}', VERSION says '${v}'" >&2
            drift=1
        fi
    done
    return "$drift"
}

case "${1:-check}" in
    sync)
        v="$(read_version)"
        [ -n "$v" ] || { echo "version: VERSION file is empty" >&2; exit 1; }
        sync_version "$v"
        echo "version: synced everything to ${v}"
        ;;
    check)
        v="$(read_version)"
        [ -n "$v" ] || { echo "version: VERSION file is empty" >&2; exit 1; }
        if check_version "$v"; then
            echo "version: all targets match ${v}"
        else
            echo "version: run 'tools/version.sh sync' and add a '## v${v}' section to CHANGELOG.md" >&2
            exit 1
        fi
        ;;
    *)
        echo "usage: $0 {sync|check}" >&2
        exit 2
        ;;
esac
